from __future__ import annotations

import math
from typing import Dict, List, Sequence, Tuple

Point = Tuple[float, float]


def _polyline(vertices: Sequence[Point], n: int = 64) -> List[Point]:
    """折れ線を、長さに比例した間隔で n 点前後に細かく分ける。"""
    segs = list(zip(vertices[:-1], vertices[1:]))
    lengths = [math.dist(a, b) for a, b in segs]
    total = sum(lengths)
    out: List[Point] = []
    for (a, b), L in zip(segs, lengths):
        k = max(2, round(n * L / total))
        out += [(a[0] + (b[0] - a[0]) * i / k, a[1] + (b[1] - a[1]) * i / k) for i in range(k)]
    out.append(tuple(vertices[-1]))
    return out


def _curve(f, n: int = 64) -> List[Point]:
    return [f(2 * math.pi * i / (n - 1)) for i in range(n)]


def _screen(points: Sequence[Point]) -> List[Point]:
    """画面座標 (y が下向き) で描いた点を x = 右, y = 上 に直し、ほかの見本と同じく
    中心 (0, 0)・縦横の大きい方が -1〜1 に収まる大きさにそろえる。"""
    xs = [x for x, _ in points]
    ys = [y for _, y in points]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    half = max(max(xs) - min(xs), max(ys) - min(ys)) / 2
    return [((x - cx) / half, (cy - y) / half) for x, y in points]


